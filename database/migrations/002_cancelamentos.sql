BEGIN;

CREATE TABLE IF NOT EXISTS solicitacoes_cancelamento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INTEGER NOT NULL REFERENCES pedido(id) ON DELETE CASCADE,
    motivo VARCHAR(1000) NOT NULL DEFAULT '',
    status VARCHAR(12) NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'aprovado', 'recusado')),
    solicitado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    respondido_em TIMESTAMPTZ,
    id_administrador INTEGER REFERENCES usuarios(id),
    CHECK ((status = 'pendente' AND respondido_em IS NULL AND id_administrador IS NULL)
        OR (status <> 'pendente' AND respondido_em IS NOT NULL AND id_administrador IS NOT NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_cancelamento_pendente
    ON solicitacoes_cancelamento(id_pedido) WHERE status = 'pendente';
CREATE INDEX IF NOT EXISTS idx_cancelamentos_pedido
    ON solicitacoes_cancelamento(id_pedido, id DESC);

-- Bancos antigos ainda ligam carrinho a pedido. Preserve o item ao excluir o pedido.
DO $$
DECLARE
    restricao RECORD;
    coluna SMALLINT;
BEGIN
    SELECT attnum INTO coluna FROM pg_attribute
    WHERE attrelid = 'carrinho'::regclass AND attname = 'id_pedido' AND NOT attisdropped;
    IF coluna IS NOT NULL THEN
        ALTER TABLE carrinho ALTER COLUMN id_pedido DROP NOT NULL;
        IF NOT EXISTS (SELECT 1 FROM pg_constraint
            WHERE conrelid = 'carrinho'::regclass AND confrelid = 'pedido'::regclass
              AND contype = 'f' AND conkey = ARRAY[coluna] AND confdeltype = 'n') THEN
            FOR restricao IN SELECT conname FROM pg_constraint
                WHERE conrelid = 'carrinho'::regclass AND confrelid = 'pedido'::regclass
                  AND contype = 'f' AND conkey = ARRAY[coluna]
            LOOP
                EXECUTE format('ALTER TABLE carrinho DROP CONSTRAINT %I', restricao.conname);
            END LOOP;
            ALTER TABLE carrinho ADD CONSTRAINT fk_carrinho_pedido
                FOREIGN KEY (id_pedido) REFERENCES pedido(id) ON DELETE SET NULL;
        END IF;
    END IF;
END $$;

COMMIT;
