BEGIN;

CREATE TABLE IF NOT EXISTS artes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id),
    id_produto INTEGER UNIQUE REFERENCES produto(id) ON DELETE CASCADE,
    nome_original VARCHAR(255) NOT NULL,
    mime VARCHAR(32) NOT NULL CHECK (mime IN ('image/png', 'image/jpeg', 'image/webp', 'application/pdf')),
    tamanho INTEGER NOT NULL CHECK (tamanho > 0 AND tamanho <= 10485760),
    conteudo BYTEA NOT NULL CHECK (octet_length(conteudo) = tamanho),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_artes_rascunhos_data ON artes(criado_em) WHERE id_produto IS NULL;

COMMIT;
