<?php
// Todas as gravações dos testes usam tabelas temporárias e sequências próprias.
require_once __DIR__ . '/../include/functions.php';

function preparar_carrinho_teste($conexao)
{
    foreach (['usuarios', 'categorias', 'tipos_de_produto', 'precodimensoes', 'produto', 'pedido'] as $tabela) {
        $conexao->exec("CREATE TEMP TABLE $tabela (LIKE public.$tabela INCLUDING ALL)");
    }
    $conexao->exec('SET search_path TO pg_temp, public');
    // Estrutura antiga para testar também a migração.
    $conexao->exec('CREATE TEMP TABLE carrinho (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_usuario INT NOT NULL REFERENCES usuarios(id),
        id_pedido INT NOT NULL REFERENCES pedido(id))');
    $conexao->exec('ALTER TABLE produto ADD FOREIGN KEY (id_categoria) REFERENCES categorias(id),
        ADD FOREIGN KEY (id_tipo) REFERENCES tipos_de_produto(id)');
    $conexao->exec('ALTER TABLE pedido ADD FOREIGN KEY (id_usuario) REFERENCES usuarios(id),
        ADD FOREIGN KEY (id_produto) REFERENCES produto(id)');
    $conexao->exec("INSERT INTO usuarios (nome, email, senha, admin) VALUES
        ('Cliente de teste', 'teste@example.invalid', 'teste', true),
        ('Outro cliente', 'outro@example.invalid', 'teste', false)");
    $conexao->exec("INSERT INTO categorias (nome) VALUES ('Adesivos'), ('Papelaria'), ('Placas'), ('Banners')");
    $conexao->exec("INSERT INTO tipos_de_produto (id_categoria, nome, valor_base) VALUES
        (1, 'BOPP', 5.00), (1, 'Vinil', 7.50), (1, 'Vinil UV', 10.00),
        (4, 'PVC', 2.00), (4, 'Madeira', 3.00), (4, 'Alumínio', 4.00), (4, 'Ilhós', 2.50),
        (2, 'Sulfite', 0.50), (2, 'Fotográfico', 1.50), (2, 'Couché', 1.00), (2, 'Offset', 0.75)");
    $conexao->exec('INSERT INTO produto (id_categoria, quantidade, largura, comprimento, id_tipo) VALUES
        (1, 2, 100, 100, 1), (1, 3, 100, 100, 1), (1, 1, 100, 100, 1), (1, 1, 100, 100, 1)');
    $conexao->exec("INSERT INTO pedido (id_usuario, id_produto, data, status, preco_unitario, valor_total) VALUES
        (1, 1, CURRENT_TIMESTAMP, 'carrinho', 1.25, 2.50),
        (1, 2, CURRENT_TIMESTAMP, 'carrinho', 0.34, 1.02),
        (2, 3, CURRENT_TIMESTAMP, 'carrinho', 999.00, 999.00),
        (1, 4, CURRENT_TIMESTAMP, 'pendente', 50.00, 50.00)");
    $conexao->exec('INSERT INTO carrinho (id_usuario, id_pedido) VALUES (1, 1), (1, 2), (2, 3)');
    $sql = file_get_contents(__DIR__ . '/../docs/carrinho_em_verificacao.pgsql');
    $sql = preg_replace('/^(BEGIN;|COMMIT;)\r?\n?/m', '', $sql);
    $conexao->beginTransaction();
    try {
        $conexao->exec($sql);
        $conexao->commit();
    } catch (Throwable $e) {
        $conexao->rollBack();
        throw $e;
    }
}
